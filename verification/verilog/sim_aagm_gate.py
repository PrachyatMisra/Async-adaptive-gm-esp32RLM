#!/usr/bin/env python3
"""Reference model of the AAGM terminal-event policy (aagm_gate.v).

EXECUTION SOURCE: reference_simulation.

This is NOT an RTL simulation. It is a Python re-implementation of the
control contract expressed in aagm_gate.v, used only as a fallback when
Icarus Verilog is not installed, and as the generator of the cross-check
vector file that is replayed against the real RTL when Icarus Verilog *is*
available (see `make crosscheck`).

The model is deliberately a direct transcription of the RTL equations, so
that a disagreement between the two is a genuine finding rather than a
restatement of the same expectation.

Usage:
    sim_aagm_gate.py                    run the vector suite, emit a reference VCD
    sim_aagm_gate.py --emit-vectors F   write the vector file used by the
                                        RTL cross-check (one vector per line)
    sim_aagm_gate.py --check-vcd F      replay a VCD and verify that every
                                        recorded terminal event matches the
                                        model
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# --- Constants (mirrors aagm_gate.v) ---------------------------------------
THRESHOLD_Q15 = 29491  # 0.900 in Q1.15, matching RLM_HALT_EPS = 0.1
MASS_BITS = 18        # unsigned Q3.15, matching the RTL mass input width

REASON_NONE = 0b00
REASON_ACT = 0b01
REASON_BUDGET = 0b10
REASON_ABORT = 0b11

REASON_NAMES = {
    REASON_NONE: "none",
    REASON_ACT: "act",
    REASON_BUDGET: "budget",
    REASON_ABORT: "abort",
}

# --- The vector suite -------------------------------------------------------
# GATE_VECTORS holds the INPUTS only. The expectations are computed by
# classify(), so that the cross-check vector file really is the output of
# the reference model rather than a transcription of it.
#
# (name, step_valid, min_steps_reached, budget_exhausted, async_abort,
#  halting_mass_q15)
GATE_VECTORS = [
    ("Idle: step_valid=0",              0, 1, 0, 0, 30000),
    ("Min steps not reached",           1, 0, 0, 0, 30000),
    ("Mass just below threshold",       1, 1, 0, 0, 29490),
    ("Mass at threshold -> ACT halt",   1, 1, 0, 0, 29491),
    ("Mass far above threshold",        1, 1, 0, 0, 131072),
    ("Budget exhausted -> termination", 1, 1, 1, 0, 29491),
    ("Budget and min steps not reached", 1, 0, 1, 0, 29491),
    ("Abort requested -> exclusive",    1, 1, 0, 1, 29491),
    ("Abort suppresses the ACT halt",   1, 1, 0, 1, 131072),
    ("Abort without a valid step",      0, 1, 0, 1, 30000),
    ("Abort and budget together",       1, 1, 1, 1, 29491),
    ("No terminal event",               1, 1, 0, 0, 1000),
]

# A hand-written oracle, kept separate from classify() on purpose: it is
# what catches a regression in the reference model itself. The cross-check
# vector file is generated from classify(), not from this table.
#
# (exp_halt, exp_halt_budget, exp_abort, exp_reason)
EXPECTED = [
    (0, 0, 0, REASON_NONE),
    (0, 0, 0, REASON_NONE),
    (0, 0, 0, REASON_NONE),
    (1, 0, 0, REASON_ACT),
    (1, 0, 0, REASON_ACT),
    (0, 1, 0, REASON_BUDGET),
    (0, 1, 0, REASON_BUDGET),
    (0, 0, 1, REASON_ABORT),
    (0, 0, 1, REASON_ABORT),
    (0, 0, 1, REASON_ABORT),
    (0, 0, 1, REASON_ABORT),
    (0, 0, 0, REASON_NONE),
]


def classify(step_valid: int, min_steps_reached: int, budget_exhausted: int,
             async_abort: int, halting_mass_q15: int) -> tuple[int, int, int, int]:
    """Transcription of aagm_gate.v. Returns (halt, halt_budget, abort, reason)."""
    abort = 1 if async_abort else 0
    halt = 1 if (step_valid and min_steps_reached and not budget_exhausted
                 and not async_abort
                 and halting_mass_q15 >= THRESHOLD_Q15) else 0
    halt_budget = 1 if (step_valid and budget_exhausted and not async_abort) else 0
    if abort:
        reason = REASON_ABORT
    elif halt:
        reason = REASON_ACT
    elif halt_budget:
        reason = REASON_BUDGET
    else:
        reason = REASON_NONE
    return halt, halt_budget, abort, reason


def write_vcd(vcd_path: Path, trace: list) -> None:
    """Write an IEEE 1364 VCD waveform file for the reference run.

    The file is deliberately NOT named aagm_gate.vcd: that name belongs to
    the genuine Icarus Verilog waveform, which this fallback must never
    overwrite.
    """
    with open(vcd_path, "w") as f:
        f.write("$date\n   generated by sim_aagm_gate.py (reference model)\n$end\n")
        f.write("$version\n   AAGM reference model (NOT a Verilog simulation)\n$end\n")
        f.write("$timescale\n   1ns\n$end\n")
        f.write("$scope module tb_aagm_gate $end\n")
        f.write("$var wire 1 ! step_valid $end\n")
        f.write("$var wire 1 \" min_steps_reached $end\n")
        f.write("$var wire 1 # budget_exhausted $end\n")
        f.write("$var wire 1 $ async_abort $end\n")
        f.write(f"$var wire {MASS_BITS} % halting_mass_q15 [{MASS_BITS - 1}:0] $end\n")
        f.write("$var wire 1 & halt $end\n")
        f.write("$var wire 1 ' halt_budget $end\n")
        f.write("$var wire 1 ( abort $end\n")
        f.write("$var wire 2 ) halt_reason [1:0] $end\n")
        f.write("$upscope $end\n")
        f.write("$enddefinitions $end\n")

        for time_ns, s in trace:
            f.write(f"#{time_ns}\n")
            f.write(f"{s['step_valid']}!\n")
            f.write(f"{s['min_steps_reached']}\"\n")
            f.write(f"{s['budget_exhausted']}#\n")
            f.write(f"{s['async_abort']}$\n")
            f.write(f"b{s['halting_mass_q15']:0{MASS_BITS}b} %\n")
            f.write(f"{s['halt']}&\n")
            f.write(f"{s['halt_budget']}'\n")
            f.write(f"{s['abort']}(\n")
            f.write(f"b{s['halt_reason']:02b} )\n")


def emit_vectors(path: Path) -> int:
    """Write the vector file consumed by tb_aagm_gate.v (+vectors=<file>).

    The expectations are the output of classify(), so the RTL is checked
    against the live reference model and not against a transcribed table.
    """
    with open(path, "w") as f:
        f.write("# AAGM gate cross-check vectors (generated by the reference model).\n")
        f.write("# step_valid min_steps budget_exh abort mass "
                "exp_halt exp_budget exp_abort exp_reason name\n")
        for (name, sv, ms, be, aa, mass) in GATE_VECTORS:
            eh, eb, ea, er = classify(sv, ms, be, aa, mass)
            # The Verilog $sscanf "%s" reads a single whitespace-delimited
            # token, so the name is written without spaces.
            token = name.replace(" ", "_")
            f.write(f"{sv} {ms} {be} {aa} {mass} {eh} {eb} {ea} {er} {token}\n")
    return 0


def run_suite() -> int:
    print("=" * 72)
    print("   AAGM Digital Control Policy - REFERENCE MODEL")
    print("   execution_source=reference_simulation (NOT an RTL simulation)")
    print("=" * 72)
    print(f"Model: aagm_gate.v contract | Threshold: Q1.15 >= {THRESHOLD_Q15} (0.900)")
    print("-" * 72)
    print(f"{'Vector':<46} {'Halt':<5} {'Budg':<5} {'Abrt':<5} {'Reason':<8} Result")
    print("-" * 72)

    failures = 0
    trace = []
    current_time = 0

    for (name, sv, ms, be, aa, mass), (eh, eb, ea, er) in zip(GATE_VECTORS, EXPECTED):
        halt, halt_budget, abort, reason = classify(sv, ms, be, aa, mass)

        current_time += 10
        trace.append((current_time, {
            "step_valid": sv,
            "min_steps_reached": ms,
            "budget_exhausted": be,
            "async_abort": aa,
            "halting_mass_q15": mass,
            "halt": halt,
            "halt_budget": halt_budget,
            "abort": abort,
            "halt_reason": reason,
        }))

        ok = (halt, halt_budget, abort, reason) == (eh, eb, ea, er)
        if not ok:
            failures += 1
            res = (f"FAIL (exp halt={eh} budget={eb} abort={ea} "
                   f"reason={REASON_NAMES[er]})")
        else:
            res = "PASS"

        print(f"{name:<46} {halt:<5} {halt_budget:<5} {abort:<5} "
              f"{REASON_NAMES[reason]:<8} {res}")

    vcd_out = Path(__file__).resolve().parent / "aagm_gate_ref.vcd"
    write_vcd(vcd_out, trace)
    print("-" * 72)
    print(f"Reference VCD -> {vcd_out.name}  (does not overwrite the Icarus waveform)")

    if failures == 0:
        print("AAGM_REFERENCE_PASS")
        return 0
    print(f"AAGM_REFERENCE_FAIL count={failures}")
    return 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--emit-vectors", metavar="PATH",
                    help="write the RTL cross-check vector file and exit")
    args = ap.parse_args()
    if args.emit_vectors:
        emit_vectors(Path(args.emit_vectors))
        return 0
    return run_suite()


if __name__ == "__main__":
    sys.exit(main())
